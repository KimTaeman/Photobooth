-- Tatt n' Snap production security and media model.
-- Apply with `supabase db push`, then create invited operator/admin users.

begin;

create extension if not exists pgcrypto;

create table if not exists public.settings (
  key text primary key,
  value text not null,
  updated_at timestamptz not null default now(),
  updated_by uuid references auth.users(id) on delete set null
);

create table if not exists public.sessions (
  id text primary key,
  created_at timestamptz not null default now(),
  frame text,
  has_video boolean not null default false
);

create table if not exists public.admin_logs (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  action text not null,
  actor_id uuid references auth.users(id) on delete set null default auth.uid()
);

alter table public.settings add column if not exists updated_at timestamptz not null default now();
alter table public.settings add column if not exists updated_by uuid references auth.users(id) on delete set null;
alter table public.admin_logs add column if not exists actor_id uuid references auth.users(id) on delete set null default auth.uid();

create table if not exists public.media_assets (
  id uuid primary key default gen_random_uuid(),
  session_id text not null references public.sessions(id) on delete cascade,
  cloudinary_asset_id text unique,
  public_id text not null unique,
  resource_type text not null check (resource_type in ('image', 'video', 'raw')),
  asset_kind text not null check (asset_kind in ('photo', 'gif', 'video')),
  mime_type text,
  byte_size bigint check (byte_size is null or byte_size >= 0),
  format text,
  width integer check (width is null or width > 0),
  height integer check (height is null or height > 0),
  secure_url text,
  status text not null default 'pending' check (status in ('pending', 'uploaded', 'failed', 'deleted')),
  created_at timestamptz not null default now(),
  expires_at timestamptz not null default (now() + interval '24 hours'),
  uploaded_at timestamptz,
  deleted_at timestamptz,
  last_error text
);

alter table public.media_assets
  add column if not exists authorized_by uuid references auth.users(id) on delete set null;

create table if not exists public.upload_authorizations (
  id bigint generated always as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  session_id text not null,
  created_at timestamptz not null default now()
);

create index if not exists upload_authorizations_rate_idx
  on public.upload_authorizations (user_id, created_at desc);

create index if not exists media_assets_session_idx on public.media_assets (session_id);
create index if not exists media_assets_expiration_idx
  on public.media_assets (expires_at)
  where deleted_at is null;

create or replace function public.app_role()
returns text
language sql
stable
set search_path = ''
as $$
  select coalesce(auth.jwt() -> 'app_metadata' ->> 'role', '');
$$;

create or replace function public.is_admin()
returns boolean
language sql
stable
set search_path = ''
as $$
  select public.app_role() = 'admin';
$$;

create or replace function public.is_operator()
returns boolean
language sql
stable
set search_path = ''
as $$
  select public.app_role() in ('operator', 'admin');
$$;

revoke all on function public.app_role() from public;
revoke all on function public.is_admin() from public;
revoke all on function public.is_operator() from public;
grant execute on function public.app_role() to authenticated;
grant execute on function public.is_admin() to authenticated;
grant execute on function public.is_operator() to authenticated;

alter table public.settings enable row level security;
alter table public.settings force row level security;
alter table public.sessions enable row level security;
alter table public.sessions force row level security;
alter table public.admin_logs enable row level security;
alter table public.admin_logs force row level security;
alter table public.media_assets enable row level security;
alter table public.media_assets force row level security;
alter table public.upload_authorizations enable row level security;
alter table public.upload_authorizations force row level security;

revoke all on table public.settings, public.sessions, public.admin_logs, public.media_assets
  from public, anon, authenticated;
revoke all on table public.upload_authorizations from public, anon, authenticated;

-- Public share and kiosk screens may read configuration, but only admins mutate it.
grant select (key, value, updated_at) on public.settings to anon, authenticated;
grant insert, update, delete on public.settings to authenticated;

drop policy if exists "settings are publicly readable" on public.settings;
drop policy if exists "admins insert settings" on public.settings;
drop policy if exists "admins update settings" on public.settings;
drop policy if exists "admins delete settings" on public.settings;

create policy "settings are publicly readable"
on public.settings for select to anon, authenticated using (true);
create policy "admins insert settings"
on public.settings for insert to authenticated with check ((select public.is_admin()));
create policy "admins update settings"
on public.settings for update to authenticated
using ((select public.is_admin())) with check ((select public.is_admin()));
create policy "admins delete settings"
on public.settings for delete to authenticated using ((select public.is_admin()));

-- A kiosk must be signed in as an operator. Guests cannot enumerate sessions.
grant insert (id, frame, has_video) on public.sessions to authenticated;
grant select, delete on public.sessions to authenticated;

drop policy if exists "operators insert validated sessions" on public.sessions;
drop policy if exists "admins read sessions" on public.sessions;
drop policy if exists "admins delete sessions" on public.sessions;
drop policy if exists "public kiosk may insert sessions" on public.sessions;
drop policy if exists "public kiosk session validation" on public.sessions;

create policy "operators insert validated sessions"
on public.sessions for insert to authenticated
with check (
  (select public.is_operator())
  and id ~ '^session_[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$'
  and frame = any (array['/frame1.png', '/frame2.png', '/frame3.png', '/frame4.png']::text[])
  and has_video is not null
);
create policy "admins read sessions"
on public.sessions for select to authenticated using ((select public.is_admin()));
create policy "admins delete sessions"
on public.sessions for delete to authenticated using ((select public.is_admin()));

grant select, insert on public.admin_logs to authenticated;
do $$
begin
  if to_regclass('public.admin_logs_id_seq') is not null then
    execute 'grant usage, select on sequence public.admin_logs_id_seq to authenticated';
  end if;
end;
$$;
drop policy if exists "admins read audit logs" on public.admin_logs;
drop policy if exists "admins write audit logs" on public.admin_logs;
create policy "admins read audit logs"
on public.admin_logs for select to authenticated using ((select public.is_admin()));
create policy "admins write audit logs"
on public.admin_logs for insert to authenticated
with check ((select public.is_admin()) and actor_id = auth.uid() and char_length(action) between 1 and 500);

-- Media rows are server-owned. Admins can inspect lifecycle metadata but Edge
-- Functions perform all writes with the service role.
grant select on public.media_assets to authenticated;
drop policy if exists "admins read media metadata" on public.media_assets;
create policy "admins read media metadata"
on public.media_assets for select to authenticated using ((select public.is_admin()));

create or replace function public.update_settings(updates jsonb)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  setting record;
  allowed_keys constant text[] := array[
    'event_theme', 'theme', 'available_frames', 'countdown_duration',
    'capture_delay', 'enable_video', 'active_filter', 'enable_pdpa',
    'pdpa_text_en', 'pdpa_text_th', 'enable_stickers', 'enable_boomerang',
    'layout_2x2', 'frame_layouts'
  ];
begin
  if not public.is_admin() then
    raise exception 'admin role required' using errcode = '42501';
  end if;

  if jsonb_typeof(updates) <> 'object'
     or (select count(*) from jsonb_object_keys(updates)) > 20 then
    raise exception 'invalid settings payload' using errcode = '22023';
  end if;

  for setting in select key, value from jsonb_each_text(updates)
  loop
    if not (setting.key = any (allowed_keys)) or char_length(setting.value) > 10000 then
      raise exception 'invalid setting: %', setting.key using errcode = '22023';
    end if;

    insert into public.settings (key, value, updated_at, updated_by)
    values (setting.key, setting.value, now(), auth.uid())
    on conflict (key) do update
      set value = excluded.value,
          updated_at = excluded.updated_at,
          updated_by = excluded.updated_by;
  end loop;
end;
$$;

revoke all on function public.update_settings(jsonb) from public, anon;
grant execute on function public.update_settings(jsonb) to authenticated;

commit;
